// Topics that are guides from the guide carousel / help requests: they carry the "reading this changed
// nothing" line that the guide texts always had.
const STANDALONE = new Set(["what-can-do", "installment-help", "how-to-record", "correction-reply", "delete-data"]);

export function guideCardSpec(id: string, open: (path: string) => string): GuideCardSpec | null {
  const spec = GUIDE_SPECS[id];
  if (!spec) return null;
  return { ...spec(open), guideNote: !STANDALONE.has(id) };
}

/** The card for a guide id ("what-can-do", "multi_record", "start", ...), or null when there is none. */
export function guideCard(id: string, appOrigin?: string): FlexMessage | null {
  const spec = guideCardSpec(id, (path) => miniAppUrl(path, appOrigin));
  return spec ? buildGuideCard(spec, appOrigin) : null;
}
