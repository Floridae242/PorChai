export type HelpTopic = OnboardingTopic | keyof typeof EXTRA_HELP;
/** High-confidence how-to requests are intercepted before every pending financial flow. */
export function readHelpRequest(
  message: string,
): { topic: HelpTopic | null } | null {
  if (message.length > 600) return null;
  const s = message.normalize("NFC").trim().toLowerCase();
  if (/^(?:ไม่ต้อง|ไม่เอา|ไม่ขอ).*(?:สอน|คู่มือ|วิธีใช้)/u.test(s)) return null;
  const cue =
    /ขอ(?:ดู)?(?:วิธี|คู่มือ)|ช่วย(?:บอก|แนะนำ|สอน)|ทำ(?:ยังไง|อย่างไร)(?:ถึง|ให้|เพื่อ)|(?:ใช้|จด|ผ่อน|รับแต้ม|ตั้งงบ|เริ่ม).*(?:ยังไง|อย่างไร)|(?:ยังไง|อย่างไร|ทำไม่เป็น|ใช้ไม่เป็น|เริ่มตรงไหน)(?:ครับ|ค่ะ|คะ|หน่อย|นะ|\s|[?？])*$/u.test(
      s,
    ) ||
    /^(?:คู่มือ|วิธีใช้|วิธีการ|ดูวิธี|สอน(?:ใช้|ผ่อน|จด|หน่อย|การ)|เริ่มใช้งาน|แนะนำการใช้|อยากรู้วิธี|ไม่(?:รู้|เข้าใจ)(?:วิธี|การใช้)|help\b|how\s+to\b|ใช้งานไม่เป็น|ทำอะไรได้บ้าง)/iu.test(
      s,
    );
  if (!cue) return null;
  if (/ทั้งหมด|ทุก(?:ฟีเจอร์|feature|อย่าง|เรื่อง|วิธี)/iu.test(s))
    return { topic: null };
  const groups: [RegExp, HelpTopic][] = [
    [/ลบข้อมูล|ส่วนตัว|privacy/u, "privacy"],
    [/แก้รายการ|แก้รายจ่าย|ลบรายการ|ลบรายจ่าย|edit|delete/u, "edit"],
    [/ocr|สแกน|ใบเสร็จ|สลิป|ส่งรูป/u, "scan"],
    [/ค้น|search/u, "search"],
    [/ยอดเงินจริง|ปรับยอด|ยอดคงเหลือ|balance/u, "balance"],
    [/ค่าอาหาร|ค่ากิน|ค่ารถ|ค่าเดินทาง|จำเป็น/u, "essentials"],
    [/วันรับเงิน|วันเงินเข้า/u, "payday"],
    [/เงินเผื่อ|ฉุกเฉิน/u, "buffer"],
    [/เตือนจด|เตือนรายการ|ลืมจด/u, "reminders"],
    [/แต้ม|คะแนน|แลกของ|รางวัล|point|reward/u, "points"],
    [/หมวด|งบรายหมวด|ตั้งงบ|category/u, "categories"],
    [/แจ้งเตือน|เตือนงบ|สรุปรายวัน|สรุปรายเดือน|notify/u, "notify"],
    [/ผ่อน|งวด|บิล|แผนซื้อ|installment/u, "plans"],
    [/รายงาน|ภาพรวม|วิเคราะห์|สรุป|แพทเทิร์น|report/u, "reports"],
    [/ก่อนจ่าย|ก่อนซื้อ|ลองซื้อ|ซื้อไหว|ลองก่อน/u, "decide"],
    [/รายรับ|รับเงิน|ได้เงิน|เงินเข้า|income/u, "income"],
    [/คูปอง|โฆษณา|โปร(?!แกรม|เจก)/u, "promos"],
    [/เริ่มรอบ|รอบเงิน|ตั้งแผน|setup/u, "start"],
    [/จด|บันทึก|รายจ่าย|expense/u, "record"],
  ];
  return { topic: groups.find(([pattern]) => pattern.test(s))?.[1] ?? null };
}
